-- Справочник грузов для помощника ввода в «Задании» (Влад 11.09: «начинаю вводить BG - предлагает Bauer BG 40,
-- jcb 3 - 3CX, морск - морской контейнер 20/40 футов, быт - стандартная бытовка; Д×Ш×В и вес заполняются
-- автоматически, но с примечанием "проверить"»). Данные - типовые транспортные габариты из открытых спецификаций
-- производителей, ОРИЕНТИР, не паспорт конкретной машины: у каждой автоподстановки в заявке остаётся пометка
-- «проверить». Правится в Справочниках, растёт от истории заявок (plan_orders.cargo) автоматически.
-- Идемпотентно: INSERT IGNORE по name.
CREATE TABLE IF NOT EXISTS plan_cargo_catalog (
  id INT NOT NULL AUTO_INCREMENT,
  name VARCHAR(150) NOT NULL,                     -- как подставляется в поле «Груз»
  aliases VARCHAR(300) DEFAULT NULL,              -- через | : латиница/кириллица/сокращения для поиска
  category VARCHAR(60) DEFAULT NULL,              -- экскаватор | бульдозер | каток | погрузчик | буровая | контейнер | бытовка | ...
  length_m DECIMAL(6,2) DEFAULT NULL,
  width_m DECIMAL(6,2) DEFAULT NULL,
  height_m DECIMAL(6,2) DEFAULT NULL,
  weight_t DECIMAL(8,2) DEFAULT NULL,
  note VARCHAR(200) DEFAULT NULL,                 -- что важно логисту (снимать стрелу, мачту и т.п.)
  source VARCHAR(60) DEFAULT 'спецификация',
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_by VARCHAR(255) DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_name (name),
  KEY idx_category (category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

