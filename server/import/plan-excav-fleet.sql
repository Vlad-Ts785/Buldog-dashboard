-- JCB-погрузчики/фронталы/компрессоры/катки/бульдозеры/самосвалы), листы "Наемные"/"Список"/сводки/долги/навесное
-- сознательно исключены (не «наша техника» либо шумные вторичные подборки). Идемпотентно: INSERT IGNORE по
-- gos_number. Правится в Справочниках (см. отдельный фронт-таск).
CREATE TABLE IF NOT EXISTS plan_fleet_excavators (
  id INT NOT NULL AUTO_INCREMENT,
  gos_number VARCHAR(20) NOT NULL,                -- госномер как в справочнике экскаваторщиков, напр. «1470 НА 50»
  model VARCHAR(120) NOT NULL,                    -- марка/модель как в их файле, напр. «JCB-205»
  category VARCHAR(60) NOT NULL,                  -- экскаватор гусеничный | экскаватор колёсный | ...
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_gos_number (gos_number),
  KEY idx_category (category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

